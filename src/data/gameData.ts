export function getFloorConfig(floor: number): FloorConfig {
  if (floor <= FLOOR_CONFIGS.length) {
    return FLOOR_CONFIGS[floor - 1];
  }
  // Procedural Endless Abyss scaling for Floor 6+
  const base = FLOOR_CONFIGS[(floor - 1) % FLOOR_CONFIGS.length];
  const scale = 1 + (floor - 5) * 0.28;
  return {
    ...base,
    floor,
    nameKo: `무한 심연 ${floor}층 : ${base.nameKo}`,
    nameEn: `Abyss Floor ${floor}: ${base.nameEn}`,
    subtitleKo: '끝없는 심연의 시련 — 고득점 신기록에 도전하세요!',
    subtitleEn: 'Endless Abyssal Trial — Push your high score to the limit!',
    boss: {
      ...base.boss,
      nameKo: `심연 각성 ${base.boss.nameKo}`,
      nameEn: `Awakened ${base.boss.nameEn}`,
      maxHp: Math.round(base.boss.maxHp * scale),
      atk: Math.round(base.boss.atk * (1 + (floor - 5) * 0.18)),
      def: base.boss.def + (floor - 5) * 2,
      goldReward: Math.round(base.boss.goldReward * scale),
      scoreReward: Math.round(base.boss.scoreReward * scale),
    },
    monsters: base.monsters.map((m) => ({
      ...m,
      unit: {
        ...m.unit,
        maxHp: Math.round(m.unit.maxHp * scale),
        atk: Math.round(m.unit.atk * (1 + (floor - 5) * 0.16)),
        def: m.unit.def + (floor - 5),
        goldReward: Math.round(m.unit.goldReward * scale),
        scoreReward: Math.round(m.unit.scoreReward * scale),
      },
    })),
  };
}
